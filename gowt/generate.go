package gowt

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/printer"
	"go/token"
	"sort"
	"strings"
	"text/template"

	"golang.org/x/tools/go/ast/astutil"
)

// genContext is the data passed to the output template.
type genContext struct {
	Package             string
	Imports             []ImportSpec
	SourceFile          string   // base name of the _gowt.go template file
	ConstraintAssertion string   // compile-time constraint check (empty = none)
	Decls               []string // substituted declaration source texts, in order
}

var outputTemplate = template.Must(template.New("gowt").Parse(
	`// Code generated by gowt from {{.SourceFile}}. DO NOT EDIT.

package {{.Package}}

import (
{{- range .Imports}}
{{- if .Alias}}
	{{.Alias}} {{printf "%q" .Path}}
{{- else}}
	{{printf "%q" .Path}}
{{- end}}
{{- end}}
)
{{- if .ConstraintAssertion}}

// Compile-time check: base type must satisfy the template constraint.
var {{.ConstraintAssertion}}
{{- end}}
{{range .Decls}}
{{.}}
{{end}}`))

// generateSource renders ctx to a gofmt-formatted Go source file.
func generateSource(ctx genContext) ([]byte, error) {
	ctx.Imports = dedupeImports(ctx.Imports)

	var buf bytes.Buffer
	if err := outputTemplate.Execute(&buf, ctx); err != nil {
		return nil, fmt.Errorf("template: %w", err)
	}
	out, err := format.Source(buf.Bytes())
	if err != nil {
		return buf.Bytes(), fmt.Errorf("gofmt: %w\n--- unformatted ---\n%s", err, buf.String())
	}
	return out, nil
}

// SubstParams holds all substitution parameters for a single instantiation.
type SubstParams struct {
	TmplName   string            // template type name (e.g. "Environment")
	TypeParam  string            // type parameter name (e.g. "Base")
	Constraint string            // type parameter constraint (e.g. "epi.Environment"); "any" or "" = no check
	TargetName string            // generated type name (e.g. "MyEnv")
	BasePkg    string            // base type package alias (e.g. "common")
	BaseType   string            // base type unqualified name (e.g. "Environment")
	BasePtr    bool              // whether the base type is a pointer
	Ctor       string            // "pkg.Func" form of the constructor
	Renames    map[string]string // optional explicit renames: old → new
	UsingAlias string            // resolved alias for the PACKAGE. placeholder (empty = local)
}

// substituteDecls applies all template substitutions to gf's AST and returns
// the rendered source text of every non-import top-level declaration.
//
// Substitutions, in order:
//
//  0. Explicit renames from the "renaming" clause (all word-boundary occurrences).
//  1. *TmplName*[...] (IndexExpr/IndexListExpr containing TmplName) → *TargetName*  (pre-order).
//  2. TypeParams stripped from type and func declarations                        (pre-order).
//  3. TypeParam in KeyValueExpr key position → unqualified BaseType             (post-order).
//  4. TypeParam in all other positions → [*]BasePkg.BaseType                    (post-order).
//  5. Bare *TmplName* (with optional prefix/suffix) → *TargetName*             (post-order).
//     Idents in Sel position of a SelectorExpr (e.g. epi.Environment) are left
//     untouched, which is more precise than the former regex approach.
//  6. NEW → CtorPkg.CtorFunc                                                    (post-order).
//  7. PACKAGE.Sel → UsingAlias.Sel, or bare Sel when UsingAlias=""              (post-order).
//
// Steps 1 and 2 run in pre-order so that the type-parameter list is removed
// before its idents (which carry the TypeParam name) would otherwise be visited
// by the post-order handlers.
func substituteDecls(gf *GowtFile, p SubstParams) ([]string, error) {
	ctorPkg, ctorFunc, ok := strings.Cut(p.Ctor, ".")
	if !ok {
		return nil, fmt.Errorf("ctor %q: expected pkg.Func form", p.Ctor)
	}

	baseTypeExpr := buildTypeExpr(p.BasePkg, p.BaseType, p.BasePtr)

	// Reject PACKAGE.NEW: NEW belongs to the "via" package; PACKAGE. belongs to
	// the "using" package.  Combining them into a single selector is contradictory
	// and would produce a malformed AST (SelectorExpr.Sel must be *ast.Ident,
	// but step 6 would try to replace it with a *ast.SelectorExpr).
	var packageNEWPos token.Pos
	astutil.Apply(gf.File, func(c *astutil.Cursor) bool {
		sel, ok := c.Node().(*ast.SelectorExpr)
		if !ok {
			return true
		}
		xid, ok := sel.X.(*ast.Ident)
		if ok && xid.Name == "PACKAGE" && sel.Sel.Name == "NEW" {
			packageNEWPos = sel.Pos()
			return false
		}
		return true
	}, nil)
	if packageNEWPos.IsValid() {
		return nil, fmt.Errorf("%s: PACKAGE.NEW is not valid: NEW refers to the \"via\" constructor package, PACKAGE. refers to the \"using\" package; use them separately",
			gf.Fset.Position(packageNEWPos))
	}

	// tmplNameMatch checks whether name contains TmplName and returns the
	// prefix and suffix around it.  A zero-length TmplName never matches.
	tmplNameMatch := func(name string) (prefix, suffix string, ok bool) {
		if p.TmplName == "" {
			return "", "", false
		}
		i := strings.Index(name, p.TmplName)
		if i < 0 {
			return "", "", false
		}
		return name[:i], name[i+len(p.TmplName):], true
	}

	astutil.Apply(gf.File,
		// Pre-order: act before children are visited.
		func(c *astutil.Cursor) bool {
			switch n := c.Node().(type) {
			// Step 2: nil out TypeParams before the FieldList is traversed,
			// so the TypeParam ident inside the parameter list is never seen
			// by the post-order handlers below.
			case *ast.TypeSpec:
				n.TypeParams = nil
			case *ast.FuncDecl:
				n.Type.TypeParams = nil

			// Step 1: TmplName[Arg] → TargetName.
			// Replace the whole instantiation expression before its Index child
			// (which carries the TypeParam ident) would be visited.
			// Preserve the X ident's position so the printer keeps correct layout.
			case *ast.IndexExpr:
				id, ok := n.X.(*ast.Ident)
				if !ok {
					return true
				}
				if prefix, suffix, ok := tmplNameMatch(id.Name); ok {
					c.Replace(&ast.Ident{NamePos: id.NamePos, Name: prefix + p.TargetName + suffix})
					return false // children collapsed
				}
			case *ast.IndexListExpr:
				id, ok := n.X.(*ast.Ident)
				if !ok {
					return true
				}
				if prefix, suffix, ok := tmplNameMatch(id.Name); ok {
					c.Replace(&ast.Ident{NamePos: id.NamePos, Name: prefix + p.TargetName + suffix})
					return false
				}
			}
			return true
		},
		// Post-order: ident and selector substitutions after children.
		func(c *astutil.Cursor) bool {
			switch n := c.Node().(type) {
			case *ast.Ident:
				// Step 0: explicit renames take highest priority.
				if newName, ok := p.Renames[n.Name]; ok {
					c.Replace(&ast.Ident{NamePos: n.NamePos, Name: newName})
					return true
				}

				// Steps 3+4: TypeParam.
				if n.Name == p.TypeParam {
					_, inKV := c.Parent().(*ast.KeyValueExpr)
					if inKV && c.Name() == "Key" {
						// Struct-literal field key: unqualified base type name only.
						c.Replace(&ast.Ident{NamePos: n.NamePos, Name: p.BaseType})
					} else {
						// Type-expression context: full [*]BasePkg.BaseType.
						// Preserve the original position so the printer does not
						// introduce spurious blank lines between struct fields.
						c.Replace(cloneTypeExprAt(baseTypeExpr, n.NamePos))
					}
					return true
				}

				// Step 6: NEW → ctor SelectorExpr.
				if n.Name == "NEW" {
					c.Replace(&ast.SelectorExpr{
						X:   &ast.Ident{NamePos: n.NamePos, Name: ctorPkg},
						Sel: &ast.Ident{Name: ctorFunc},
					})
					return true
				}

				// Step 5: bare TmplName (with optional prefix/suffix) → TargetName.
				// Skip idents in Sel position of a SelectorExpr: those are the
				// right-hand side of a qualified name (pkg.TypeName) and must not
				// be renamed even if they happen to share the TmplName.
				if prefix, suffix, ok := tmplNameMatch(n.Name); ok {
					if _, isSel := c.Parent().(*ast.SelectorExpr); isSel && c.Name() == "Sel" {
						return true
					}
					c.Replace(&ast.Ident{NamePos: n.NamePos, Name: prefix + p.TargetName + suffix})
				}

			case *ast.SelectorExpr:
				// Step 7: PACKAGE.Sel → UsingAlias.Sel  or  bare Sel.
				id, ok := n.X.(*ast.Ident)
				if !ok || id.Name != "PACKAGE" {
					return true
				}
				if p.UsingAlias != "" {
					c.Replace(&ast.SelectorExpr{
						X:   &ast.Ident{NamePos: id.NamePos, Name: p.UsingAlias},
						Sel: n.Sel,
					})
				} else {
					c.Replace(n.Sel)
				}
			}
			return true
		},
	)

	// Render each non-import declaration, preserving inline comments (those
	// within the declaration body) but excluding doc comments.  Doc comments
	// are template-internal (they may reference placeholders like NEW or the
	// type-parameter syntax) and should not appear in generated output.
	// The printer uses the Doc field directly, so we must nil it out in addition
	// to filtering the file-level comments list.
	var decls []string
	for _, d := range gf.File.Decls {
		if gd, ok := d.(*ast.GenDecl); ok && gd.Tok == token.IMPORT {
			continue
		}
		stripDocComments(d)
		var buf bytes.Buffer
		if err := printer.Fprint(&buf, gf.Fset, &printer.CommentedNode{
			Node:     d,
			Comments: inlineComments(gf.File.Comments, d.Pos(), d.End()),
		}); err != nil {
			return nil, fmt.Errorf("rendering declaration: %w", err)
		}
		decls = append(decls, buf.String())
	}
	return decls, nil
}

// stripDocComments nils out the Doc field on a declaration and on any TypeSpec
// specs it contains.  Doc comments are template-internal and must not appear
// in generated output.
func stripDocComments(d ast.Decl) {
	switch n := d.(type) {
	case *ast.GenDecl:
		n.Doc = nil
		for _, spec := range n.Specs {
			if ts, ok := spec.(*ast.TypeSpec); ok {
				ts.Doc = nil
				ts.Comment = nil
			}
		}
	case *ast.FuncDecl:
		n.Doc = nil
	}
}

// inlineComments returns the subset of cgs whose position falls strictly
// within [start, end), i.e. comments that are inside a declaration body
// rather than preceding it as doc comments.
func inlineComments(cgs []*ast.CommentGroup, start, end token.Pos) []*ast.CommentGroup {
	var out []*ast.CommentGroup
	for _, cg := range cgs {
		if cg.Pos() >= start && cg.End() <= end {
			out = append(out, cg)
		}
	}
	return out
}

// buildTypeExpr constructs the AST type expression for the base type.
func buildTypeExpr(basePkg, baseType string, basePtr bool) ast.Expr {
	sel := &ast.SelectorExpr{
		X:   &ast.Ident{Name: basePkg},
		Sel: &ast.Ident{Name: baseType},
	}
	if basePtr {
		return &ast.StarExpr{X: sel}
	}
	return sel
}

// cloneTypeExprAt returns a deep copy of a simple type expression
// (Ident, SelectorExpr, or StarExpr wrapping either), anchoring the
// leading position to pos so that the printer does not insert spurious
// blank lines around the substituted node.
// A fresh copy is needed each substitution so no AST nodes are aliased.
func cloneTypeExprAt(expr ast.Expr, pos token.Pos) ast.Expr {
	switch e := expr.(type) {
	case *ast.StarExpr:
		return &ast.StarExpr{Star: pos, X: cloneTypeExprAt(e.X, pos)}
	case *ast.SelectorExpr:
		return &ast.SelectorExpr{
			X:   &ast.Ident{NamePos: pos, Name: e.X.(*ast.Ident).Name},
			Sel: &ast.Ident{Name: e.Sel.Name},
		}
	case *ast.Ident:
		return &ast.Ident{NamePos: pos, Name: e.Name}
	default:
		return e
	}
}

// dedupeImports removes duplicates and sorts (stdlib first, then third-party).
func dedupeImports(in []ImportSpec) []ImportSpec {
	seen := make(map[string]bool)
	var out []ImportSpec
	for _, imp := range in {
		if !seen[imp.Path] {
			seen[imp.Path] = true
			out = append(out, imp)
		}
	}
	sort.Slice(out, func(i, j int) bool {
		iStd := !strings.Contains(out[i].Path, ".")
		jStd := !strings.Contains(out[j].Path, ".")
		if iStd != jStd {
			return iStd
		}
		return out[i].Path < out[j].Path
	})
	return out
}
